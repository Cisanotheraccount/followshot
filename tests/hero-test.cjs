const {normalizeFooterHTML} = require('./footer-normalize.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const crypto=require('node:crypto');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=normalizeFooterHTML(fs.readFileSync(path.join(root,'site/index.html'),'utf8'));
const locale=fs.readFileSync(path.join(root,'site/site-language.js'),'utf8');
const {oldZh,newZh,oldEn,newEn,normalizeHeroHTML,normalizeHeroLocale}=require('./hero-normalize.cjs');
const baseline=require('./hero-baseline.json');
const sha=v=>crypto.createHash('sha256').update(v).digest('hex');
let count=0;const check=(v,label)=>{assert.ok(v,label);count++;console.log('PASS',label)};
check(html.split(newZh).length===2,'Requested Chinese hero sentence appears exactly once');
check(locale.split(newZh).length===2&&locale.split(newEn).length===2,'Requested Chinese and English hero translation each appears exactly once');
check(!html.includes(oldZh)&&!locale.includes(oldZh)&&!locale.includes(oldEn),'Obsolete hero subtitles are removed in both languages');
check(html.includes('把「我也想拍」变成下一步。<br>'+newZh),'Chinese first sentence and line break are preserved');
check(locale.includes('Turn “I want to try that” into a next step.<br>'+newEn),'English first sentence and line break are preserved');
check(sha(normalizeHeroHTML(html))===baseline.hashes['site/index.html'],'Hero edit changes no other HTML, layout or resource except its precise locale version');
check(sha(normalizeHeroLocale(locale))===baseline.hashes['site/site-language.js'],'Hero edit changes no other translation or language behavior');
check(normalizeHeroHTML(newZh+' typo')===oldZh+' typo','Normalization does not suppress unrelated appended text');
check(normalizeHeroHTML('different sentence')==='different sentence','Normalization never removes arbitrary copy');
check(normalizeHeroLocale('Use AI differently')==='Use AI differently','Normalization cannot hide a different English claim');
console.log(`PASS ${count} hero-copy assertions`);
